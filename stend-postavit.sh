Бэкап IvanOS: /usr/local/sbin/ivanos-backup.sh daily|weekly|proverit
Рука владельца, один раз на машину:
  1) пароль:  (umask 077; head -c 48 /dev/urandom | base64 > /root/.config/ivanos-backup/passphrase)
              и копию пароля — себе (Vaultwarden). Без него архивы не открыть никому.
