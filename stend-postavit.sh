# 🔴 Пуш НЕ валит установку. Дом без сети — живой дом; дом, который не родился из-за
# недоступного GitHub, — мёртвый. Поэтому здесь громкая строка, а не upal.
if [ "$REZHIM" = proba ]; then
  fakt "копия на GitHub" "нет — проба в GitHub не пишет (слово 04-10); ветка $(git rev-parse --abbrev-ref HEAD) только здесь"
elif [ -n "$GITHUB_DOMA" ]; then
  # 🔴 Имя ветки спрашивается у самого дома, а не собирается заново: при повторном
  # запуске установщика дом НЕ переинициализируется, и собранное имя разошлось бы
  # с настоящим — копия уехала бы в пустую новую ветку.
  VETKA=$(git rev-parse --abbrev-ref HEAD)
  if git remote get-url origin >/dev/null 2>&1; then
    git remote set-url origin "$GITHUB_DOMA"
  else
    git remote add origin "$GITHUB_DOMA"
  fi
  # 🔴 Три разных беды выглядят одинаково — «пуш не прошёл». Неверный диагноз хуже
  # отсутствия диагноза, поэтому сначала спрашиваем GitHub, что там есть.
  if ! git ls-remote --heads origin >/dev/null 2>&1; then
    echo
    echo "   🔴 КОПИИ НЕТ: до GitHub не достучаться."
    echo "   Либо на сервере нет ключа развёртывания, либо репозитория не существует."
    echo "   Проверить рукой: ssh -T git@$SSH_PSEVDONIM"
    echo "   Дом жив и работает, но снос уничтожит работу Ивана без остатка."
    echo
  else
    # Ветка на GitHub бывает СВОЯ и ЧУЖАЯ, и по одному её наличию их не отличить.
    # Своя — та, чью вершину местный дом продолжает: обычная дозапись при повторном
    # запуске установщика. Чужая — работа другой жизни того же номера.
    # 🔴 Проба 05-09 поймала: без этой развилки повторный запуск на СВОЁМ доме кричал
    # «ветка занята» и оставлял дом без копии. Идемпотентность установщика — правило.
    git fetch -q origin "$VETKA" 2>/dev/null || true
    # pipefail: обрыв сети между двумя ls-remote выходил молча (класс находки 2, 30-09) — пусто значит
    # «не узнал», и дальше пуш сам скажет «КОПИИ НЕТ».
    UDALYONNAYA=$( { git ls-remote --heads origin "$VETKA" 2>/dev/null || true; } | cut -f1)
    if [ -n "$UDALYONNAYA" ] && ! git merge-base --is-ancestor "$UDALYONNAYA" HEAD 2>/dev/null; then
      echo
      echo "   🔴 ВЕТКА $VETKA НА GitHub ЗАНЯТА ЧУЖОЙ РАБОТОЙ."
      echo "   Её вершина не лежит в истории этого дома — значит там другая жизнь"
      echo "   этого же номера. Не трогаю: затереть чужую работу установщик не вправе."
      echo "   Решение владельца: взять следующий номер поколения — или снять ветку"
      echo "   на GitHub, если та работа больше не нужна."
      echo
    # 28-09: пуш — через push_ne_main дома: цель названа, main отказывается (push-ne-main.sh).
    elif . "$DOM/push-ne-main.sh" && push_ne_main "$DOM" "$VETKA" 2>/dev/null; then
      fakt "копия на GitHub" "ветка $VETKA уехала"
    else
      echo
      echo "   🔴 КОПИИ НЕТ: GitHub отвечает, но ветку $VETKA не принял."
      echo "   У ключа развёртывания может не быть права записи."
      echo "   Дом жив и работает, но снос уничтожит работу Ивана без остатка."
      echo
    fi
  fi
else
  echo
  echo "   🔴 GITHUB_DOMA пуст — у дома нет копии. Снос уничтожит работу Ивана."
  echo
fi
}

