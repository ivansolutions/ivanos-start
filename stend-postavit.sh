token_kod() {     # <токен> — код ответа GitHub на организацию инструментов; токен не в argv
  local H KOD
  H=$(mktemp) && chmod 600 "$H"
  printf 'Authorization: Bearer %s\n' "$1" > "$H"
  KOD=$(curl -s -o /dev/null -w '%{http_code}' --max-time 15 -H @"$H" \
        -H 'Accept: application/vnd.github+json' "https://api.github.com/orgs/${INSTRUMENT_POISK%%/*}" 2>/dev/null || true)
  rm -f "$H"
  printf '%s' "${KOD:-000}"
}
okno_token() {
  local T KOD
  # 🔴 Находка 2 пробы 29-09: было `T=$(sed … "$TOKEN_FAJL" 2>/dev/null | tail -1)`. На новой машине
  # файла нет, sed отдаёт 2, pipefail несёт 2 в присваивание, set -e выходит — окно вводов молча
  # закрывалось сразу после ключей (stderr погашен). Нет файла — нет токена, это не ошибка.
  T=""
  [ ! -f "$TOKEN_FAJL" ] || T=$(sed -n 's/^GH_TOKEN=//p' "$TOKEN_FAJL" | tail -1)
  if [ -n "$T" ] && [ "$(token_kod "$T")" = 200 ]; then fakt "токен ${INSTRUMENT_POISK%%/*}" "уже есть в $TOKEN_FAJL, GitHub отвечает 200"; return 0; fi
  echo "   Токен GitHub для ${INSTRUMENT_POISK%%/*} (Иван заводит и ведёт там репозитории инструментов)."
  echo "   Вводится скрыто. Пусто — пропустить, потом: bash $SKRIPT $VERSIYA после rm $SOSTOYANIE/okno.ok"
  while :; do
    sprosit T "токен:" skryto
    [ -n "$T" ] || { fakt "токен" "пропущен — Иван не сможет заводить репозитории инструментов"; return 0; }
    KOD=$(token_kod "$T")
    [ "$KOD" = 200 ] && break
    echo "   🔴 GitHub ответил $KOD на ${INSTRUMENT_POISK%%/*} — токен не тот или без доступа. Ещё раз."
  done
  ( umask 077
    touch "$TOKEN_FAJL"
    { grep -v '^GH_TOKEN=' "$TOKEN_FAJL" || true; printf 'GH_TOKEN=%s\n' "$T"; } > "$TOKEN_FAJL.nov"
    mv "$TOKEN_FAJL.nov" "$TOKEN_FAJL" )
  chmod 600 "$TOKEN_FAJL"
  fakt "токен" "в $TOKEN_FAJL (600), GitHub ответил 200"
}
