sverka_plaginov() {
# ── Сверка генетической памяти ───────────────────────────────────────────────
# Самая важная проверка этого скрипта, и она не про то, что установилось, а про
# то, чего никто не объявлял. Плагин вне списка — это память, которую следующее
# поколение получит, не зная откуда, и объяснить себе не сможет.
# Замок обязан быть замком, а не просьбой: расхождение РОНЯЕТ установку.
# Сравниваем отсортированные списки, а не «есть ли что-то»: пропажа объявленного
# такая же ложь паспорта, как и лишнее.
# 🔴 Разбор по строке вывода, а не «что-то@что-то» по всему тексту: старый grep ловил
# любой e-mail в выводе и ронял установку на последнем шаге, когда всё уже поставлено.
STOIT=$( { claude plugin list 2>/dev/null || true; } | sed '/^Synced from claude.ai/,$d' \
         | sed -n 's/^[[:space:]]*❯[[:space:]]*\([^[:space:]]*@[^[:space:]]*\).*/\1/p' | sort | tr '\n' ' ' || true)
OBYAVLENO=$(for P in $PLAGINY_ODOBRENNYE; do echo "$P"; done | sort | tr '\n' ' ')
# 🔴 Раньше здесь стояло точное равенство, и любой плагин, поставленный Иваном по
# его же праву «один инструмент за заход», ронял установку СЛЕДУЮЩЕГО поколения —
# уже после того, как юниты подняты. Механизм наказывал за исполнение инструкции.
# Теперь: пропавшее объявленное — падение (дыра генетической памяти). Лишнее — громкая
# строка владельцу: внеси в установщик или сними. Найдено проверкой 05-09.
PROPALO=""
for O in $OBYAVLENO; do
  case " $STOIT " in *" $O "*) : ;; *) PROPALO="$PROPALO $O" ;; esac
done
LISHNIE=""
for S in $STOIT; do
  case " $OBYAVLENO " in *" $S "*) : ;; *) LISHNIE="$LISHNIE $S" ;; esac
done
if [ -n "$LISHNIE" ]; then
  echo
  echo "   🔴 СТОИТ, НО НЕ ОБЪЯВЛЕНО:$LISHNIE"
  echo "   Это либо работа Ивана по его праву, либо хвост прошлого поколения."
  echo "   Внеси в PLAGINY_ODOBRENNYE установщика — или сними командой uninstall."
  echo
fi
if [ -z "$PROPALO" ]; then
  fakt "плагины сверены" "${STOIT:-ни одного, как и объявлено}"
else
  echo
  echo "   пропало:   ${PROPALO:-пусто}"
  echo "   объявлено: ${OBYAVLENO:-пусто}"
  echo "   стоит:     ${STOIT:-пусто}"
  upal "плагины разошлись с установщиком — это и есть дыра генетической памяти.
   Либо снять лишнее (claude plugin uninstall имя@маркетплейс), либо объявить его
   в PLAGINY_ODOBRENNYE и поставить заново. Молча оставлять нельзя."
fi
# 28-09, v2: плагины «Synced from claude.ai» в сверку объявленных не идут — их не ставит никто,
# они приезжают с аккаунта. Но включённым не должен остаться ни один (решение владельца 27-09):
# f_plaginy их выключает, здесь — сверка по settings.json, а не по его выводу.
VKL_SINH=$(python3 -c 'import json;d=json.load(open("/root/.claude/settings.json")).get("enabledPlugins",{});print(" ".join(k for k,v in d.items() if k.endswith("@synced") and v))' 2>/dev/null || true)
[ -z "$VKL_SINH" ] || upal "плагины с аккаунта включены: $VKL_SINH — решение владельца 27-09 их не держать (claude plugin disable имя@synced)"
fakt "с аккаунта" "включённых нет"
fakt "живых поколений" "$(systemctl list-units 'ivanos-v*' --state=active --no-legend --no-pager | wc -l)"
}


# ── Инструмент poisk-raboty — вместе со страницей сводки ─────────────────────
# Решение владельца 27-09: инструменты — отдельные репозитории ivanos-tools, ставятся своим
# установщиком. Здесь — только взять закреплённый коммит и позвать его: время (06:00) — из
# paket.conf, а не ручным drop-in'ом; браузер — общий $BRAUZERY; сито — данные владельца в доме.
f_poisk() {
  local R=/srv/instrumenty/poisk-raboty SITO="$DOM/rabota/sito.json"
  if [ -z "${POISK_KOMMIT:-}" ]; then fakt "poisk-raboty" "в paket.conf не закреплён POISK_KOMMIT — не ставлю"; return 0; fi
  [ -d "$R/.git" ] || git clone -q --no-checkout "git@github-poisk-raboty:$INSTRUMENT_POISK.git" "$R" \
    || upal "poisk-raboty не клонируется из $INSTRUMENT_POISK"
  git -C "$R" fetch -q origin 2>/dev/null || true
  git -C "$R" -c advice.detachedHead=false checkout -q --detach "$POISK_KOMMIT" || upal "в $INSTRUMENT_POISK нет коммита $POISK_KOMMIT"
  if [ -f "$SITO" ]; then
    bash "$R/ustanovka/postavit.sh" --sito "$SITO" --vremya "${POISK_VREMYA:-07:00}" --brauzery "$BRAUZERY" \
      || upal "poisk-raboty не встал — вывод выше"
  else
    fakt "сито" "в доме нет $SITO — инструмент встанет с образцом в /etc/poisk-raboty/sito.json"
    bash "$R/ustanovka/postavit.sh" --vremya "${POISK_VREMYA:-07:00}" --brauzery "$BRAUZERY" \
      || upal "poisk-raboty не встал — вывод выше"
  fi
  fakt "poisk-raboty" "$(cat /opt/poisk-raboty/VERSIYA 2>/dev/null) @ ${POISK_KOMMIT:0:12}"
}

# ── n8n — если владелец сказал «да» ──────────────────────────────────────────
# Решение владельца 28-09: npm + sqlite, ТОЧНАЯ версия (не ^), только 127.0.0.1, копия .n8n
# перед обновлением, кэш npm после установки не оставлять. Версия и Node — строками в paket.conf.
# 🔴 n8n 2.x требует Node ≥ 24, а машина живёт на Node 22 (poisk-raboty его и проверяет). Поэтому у
# n8n СВОЙ Node в /opt/n8n/node, скачанный с nodejs.org и сверенный по sha256 из paket.conf —
# системный Node не трогается. Кэш npm — во временной папке, которая удаляется: так «~/.npm
# после не оставлять» исполнено, а кэш npx, которым живёт MCP Playwright Ивана, цел.
f_n8n() {
  local K=/opt/n8n T STARAYA OTV
  OTV=$(cat "$SOSTOYANIE/n8n.otvet" 2>/dev/null || echo net)
  if [ "$OTV" != da ]; then fakt "n8n" "не ставится — ответ владельца «нет»"; return 0; fi
  [ -n "${N8N_VERSIYA:-}" ] && [ -n "${N8N_NODE_VERSIYA:-}" ] && [ -n "${N8N_NODE_SHA256:-}" ] \
    || upal "в paket.conf не закреплены N8N_VERSIYA / N8N_NODE_VERSIYA / N8N_NODE_SHA256"
  getent passwd n8n >/dev/null || useradd --system --home-dir /var/lib/n8n --create-home --shell /usr/sbin/nologin n8n
  install -d -m 0755 "$K"
  if [ "$("$K/node/bin/node" -v 2>/dev/null)" != "$N8N_NODE_VERSIYA" ]; then
    T=$(mktemp -d)
    curl -fsSL -o "$T/node.tar.xz" "https://nodejs.org/dist/$N8N_NODE_VERSIYA/node-$N8N_NODE_VERSIYA-linux-x64.tar.xz" \
      || upal "Node $N8N_NODE_VERSIYA для n8n не скачался"
    echo "$N8N_NODE_SHA256  $T/node.tar.xz" | sha256sum -c --quiet - || upal "Node для n8n: sha256 не сошёлся с paket.conf"
    rm -rf "$K/node"; mkdir -p "$K/node"
    tar -xJf "$T/node.tar.xz" -C "$K/node" --strip-components=1
    rm -rf "$T"
  fi
  fakt "Node для n8n" "$("$K/node/bin/node" -v) в $K/node"
  STARAYA=$(cd /tmp && "$K/node/bin/node" "$K/app/node_modules/n8n/bin/n8n" --version 2>/dev/null | tail -1 || true)
  if [ "$STARAYA" != "$N8N_VERSIYA" ]; then
    if [ -n "$STARAYA" ] && [ -d /var/lib/n8n/.n8n ]; then
      systemctl stop n8n 2>/dev/null || true
      install -d -m 0700 /var/backups/n8n
      tar -czf "/var/backups/n8n/n8n-$(date +%Y%m%d-%H%M)-$STARAYA.tgz" -C /var/lib/n8n .n8n \
        || upal "копия .n8n перед обновлением не снялась — обновлять не буду"
      fakt "копия .n8n" "/var/backups/n8n/ (было $STARAYA)"
    fi
    T=$(mktemp -d)
    install -d "$K/app"
    PATH="$K/node/bin:$PATH" npm install --prefix "$K/app" --cache "$T/npm" --no-audit --no-fund \
      --save-exact --loglevel=error "n8n@$N8N_VERSIYA" > "$T/zhurnal" 2>&1 \
      || { tail -20 "$T/zhurnal"; rm -rf "$T"; upal "n8n@$N8N_VERSIYA не встал — журнал выше"; }
    rm -rf "$T"
  fi
  # 🔴 PATH юнита начинается со СВОЕГО Node — 30-09, находка 6. n8n запускает JS-раннер задач как
  # `spawn('node', …)` — по PATH (node_modules/n8n/dist/task-runners/task-runner-process-js.js:71),
  # а не своим process.execPath. Без этой строки раннер бежит на системном Node 22 вопреки
  # «системный Node не трогается» выше, а на машине без системного node (чистый корень 30-09)
  # раннер падает по кругу, и n8n через ~20 с выходит с КОДОМ 0 — Restart=on-failure его не поднимает.
  cat > /etc/systemd/system/n8n.service <<N8N
[Unit]
Description=n8n $N8N_VERSIYA (IvanOS): автоматизации, только 127.0.0.1
After=network-online.target
Wants=network-online.target

[Service]
User=n8n
Group=n8n
WorkingDirectory=/var/lib/n8n
Environment=HOME=/var/lib/n8n
Environment=PATH=$K/node/bin:/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin
Environment=N8N_LISTEN_ADDRESS=127.0.0.1
Environment=N8N_HOST=127.0.0.1
Environment=N8N_PORT=$N8N_PORT
Environment=N8N_PROTOCOL=http
Environment=N8N_SECURE_COOKIE=false
Environment=DB_TYPE=sqlite
Environment=GENERIC_TIMEZONE=Europe/Berlin
Environment=N8N_DIAGNOSTICS_ENABLED=false
Environment=N8N_VERSION_NOTIFICATIONS_ENABLED=false
ExecStart=$K/node/bin/node $K/app/node_modules/n8n/bin/n8n start
Restart=on-failure
RestartSec=10s

[Install]
WantedBy=multi-user.target
N8N
  systemd-analyze verify /etc/systemd/system/n8n.service >/dev/null 2>&1 || upal "юнит n8n не прошёл systemd-analyze verify"
  systemctl daemon-reload
  systemctl enable -q n8n
  systemctl restart n8n
  for _ in $(seq 60); do
    [ "$(curl -s -o /dev/null -w '%{http_code}' --max-time 3 "http://127.0.0.1:$N8N_PORT/healthz" 2>/dev/null)" = 200 ] && break
    sleep 3
  done
  [ "$(curl -s -o /dev/null -w '%{http_code}' --max-time 3 "http://127.0.0.1:$N8N_PORT/healthz" 2>/dev/null)" = 200 ] \
    || upal "n8n не ответил 200 на /healthz за 3 мин: journalctl -u n8n -n 40"
  fakt "n8n" "$N8N_VERSIYA на 127.0.0.1:$N8N_PORT, снаружи закрыт"
  fakt "вход в n8n" "ssh -L $N8N_PORT:127.0.0.1:$N8N_PORT root@<сервер>, потом http://localhost:$N8N_PORT"
}

