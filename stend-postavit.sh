# ── Swap: 2 ГБ, если его нет ─────────────────────────────────────────────────
# Дешёвые машины приходят без swap. Сборка npm и Chromium при нехватке памяти не падают
# словами — их убивает ядро (OOM), и журнал говорит «Killed». Первое изменение машины.
f_swap() {
  if [ "$(awk '/^SwapTotal:/{print $2}' /proc/meminfo)" != 0 ]; then
    fakt "swap" "уже есть: $(free -m | awk '/^Swap:/{print $2}') МБ"; return 0
  fi
  [ -e /swapfile ] || { fallocate -l 2G /swapfile || dd if=/dev/zero of=/swapfile bs=1M count=2048 status=none; }
  chmod 600 /swapfile
  mkswap -q /swapfile >/dev/null 2>&1 || mkswap /swapfile >/dev/null
  swapon /swapfile || upal "swapon /swapfile не прошёл"
  grep -q '^/swapfile ' /etc/fstab || echo '/swapfile none swap sw 0 0' >> /etc/fstab
  fakt "swap" "2 ГБ, /swapfile, в fstab"
}

