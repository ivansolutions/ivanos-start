  else
    IP=$(printf '%s' "$SC" | awk '{print $1}'); PORT=$(printf '%s' "$SC" | awk '{print $2}')
    ZH=$( { journalctl -t sshd -t sshd-session --no-pager -o cat -q 2>/dev/null; cat "$K/var/log/auth.log" 2>/dev/null; } \
          | grep -F "from $IP port $PORT " | grep -E 'Accepted ' | tail -1)
