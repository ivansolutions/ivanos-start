}

# ── Защита — ПЕРВОЙ, до общего apt (v2, решение владельца 28-09) ─────────────
# 27-09 на Contabo apt шёл раньше защиты (stend-postavit.sh:326 против :388): машина
# минуты стояла в интернете с паролем root. Теперь — только ufw и fail2ban, и сразу защита.
f_zashchita() {
apt-get update -qq
# ── ‹zashchita-servera› Вход только по ключу, ufw, fail2ban ─────────────────────
# 🔴 27-09, дыра «б» проверки перед Contabo. До этого README честно писал: «брандмауэра,
# fail2ban, смены ssh-порта — нет. Боевой сервер этим ставить нельзя». Contabo смотрит в
# интернет. На стенде замер 27-09: вход по паролю включён, ufw выключен, fail2ban нет.
# На старом Contabo было: вход только по ключу, fail2ban, порт 1801 (опись 27-09).
#
# Что ставится и почему так:
#   · sshd: пароль и keyboard-interactive выключены, root — только ключом. Файл зовётся
#     00-ivanos.conf НАРОЧНО: sshd берёт ПЕРВОЕ значение, а облачный образ кладёт
#     «PasswordAuthentication yes» в 50-cloud-init.conf. С именем 99-… пароль остался бы
#     включён при зелёном `sshd -t`. Итог проверяется у самого sshd (`sshd -T`), не grep'ом;
#   · 🔴 ключа владельца в authorized_keys нет — ОТКАЗ, ничего не трогаем: выключить пароль
#     без ключа значит запереть владельца снаружи собственного сервера;
#   · порт: по умолчанию 22. Свой порт — IVANOS_SSH_PORT=1801 (как на старом): это решение
#     владельца, оно снимает шум в журнале, но не заменяет ключ и fail2ban. Ubuntu 24.04
#     слушает ssh через ssh.socket; порт из sshd_config туда переносит генератор systemd
#     при daemon-reload — поэтому перезапуск сокета, а не только службы;
#   · ufw: входящие закрыты, исходящие открыты. Порт ssh открывается ДО включения — иначе
#     `ufw enable` отрезал бы и эту сессию. Живые соединения ufw не рвёт (ESTABLISHED).
#     Клетка проб живёт в своей таблице `inet proba_vNN` (proba.sh:112-128) и с ufw не
#     пересекается: чужого она не сносит, а ufw исходящих не режет. Прочие порты (80/443
#     для сайта) — IVANOS_OTKRYT="80 443", только если сайт сюда переезжает;
#   · fail2ban: тюрьма sshd на том же порту, журнал из systemd. Включённость спрашивается у
#     самого fail2ban (`fail2ban-client status sshd`), а не выводится из того, что файл лёг.
# Корень подменяется ТОЛЬКО пробой (IVANOS_KOREN) — чтобы доказать кусок, не трогая sshd
# и брандмауэр стенда. Проба: dyry-proba.sh Б.
KOREN="${IVANOS_KOREN:-}"
SSH_PORT="${IVANOS_SSH_PORT:-22}"
case "$SSH_PORT" in ''|*[!0-9]*) upal "IVANOS_SSH_PORT — число, получено «$SSH_PORT»" ;; esac
SSHD_KONF=$KOREN/etc/ssh/sshd_config
KLYUCHI_VLADELTSA=$KOREN/root/.ssh/authorized_keys
grep -qE '^(ssh-(ed25519|rsa)|ecdsa-sha2-|sk-)' "$KLYUCHI_VLADELTSA" 2>/dev/null \
  || upal "в $KLYUCHI_VLADELTSA нет ни одного ключа — выключить пароль значит запереть владельца. Сначала ключ (панель Contabo → Reinstall с ssh-ключом или ssh-copy-id), потом установщик заново"
grep -qE "^Include +$KOREN/etc/ssh/sshd_config\.d/\*\.conf" "$SSHD_KONF" \
  || upal "$SSHD_KONF не читает sshd_config.d — своё правило туда не положить"
# 🔴 04-10, проба 1 (12:53): на этом разделе оборвался ssh владельца — пришлось заходить заново и
# tmux attach. Причину с машины пробы ещё не видели; единственный перезапуск в разделе — ssh.socket, и он
# стоял безусловно, хотя нужен только при смене порта. Теперь он — только при смене порта, а связь
# владельца (ip:порт из SSH_CONNECTION) замеряется после каждого подшага: оборвётся снова — журнал
# назовёт, после чего.
svyaz() {   # <после чего>
  local SC=${IVANOS_SSH_CONNECTION:-${SSH_CONNECTION:-}} IP PORT
  [ -n "$SC" ] || return 0
  read -r IP PORT _ <<< "$SC"
  if ss -tnH state established 2>/dev/null | grep -qF -e "$IP:$PORT" -e "[$IP]:$PORT"; then
    fakt "связь владельца" "жива после: $1"
  else
    fakt "связь владельца" "🔴 ОБОРВАНА после: $1 ($IP:$PORT)"
  fi
}
apt-get install -y -qq ufw fail2ban python3-systemd >/dev/null
svyaz "apt ufw fail2ban"
SSHD_NASH=$KOREN/etc/ssh/sshd_config.d/00-ivanos.conf
{
  echo "# IvanOS, stend-postavit.sh ‹zashchita-servera›. Первое значение побеждает — потому 00."
  if [ "$SSH_PORT" != 22 ]; then echo "Port $SSH_PORT"; fi
  echo "PasswordAuthentication no"
  echo "KbdInteractiveAuthentication no"
  echo "PermitRootLogin prohibit-password"
  echo "PubkeyAuthentication yes"
} > "$SSHD_NASH"
chmod 644 "$SSHD_NASH"
if ! sshd -t -f "$SSHD_KONF" 2>/dev/null; then
  rm -f "$SSHD_NASH"
  upal "sshd -t отверг настройку — своё правило снято, sshd не трогал"
fi
ITOG_SSHD=$(sshd -T -f "$SSHD_KONF" 2>/dev/null)
grep -qx 'passwordauthentication no' <<< "$ITOG_SSHD" || upal "sshd -T: пароль всё ещё включён — чьё-то правило садится раньше 00-ivanos.conf"
grep -qx 'kbdinteractiveauthentication no' <<< "$ITOG_SSHD" || upal "sshd -T: keyboard-interactive включён"
grep -qx "port $SSH_PORT" <<< "$ITOG_SSHD" || upal "sshd -T: порт не $SSH_PORT"
ufw default deny incoming >/dev/null
ufw default allow outgoing >/dev/null
ufw allow "$SSH_PORT/tcp" >/dev/null
for P in ${IVANOS_OTKRYT:-}; do ufw allow "$P/tcp" >/dev/null; done
ufw --force enable >/dev/null
grep -q '^Status: active' <(ufw status) || upal "ufw не включился"
grep -qE "^$SSH_PORT/tcp +ALLOW" <(ufw status) || upal "ufw включён, а порт ssh $SSH_PORT не открыт — новые входы отрезаны"
svyaz "ufw enable"
systemctl daemon-reload
# Сокет перезапускается, ТОЛЬКО если он слушает не тот порт (порт сменили): пароль и kbd sshd берёт по
# reload (SIGHUP), сокет для этого не нужен. Нет сокетной активации — нечего перезапускать.
if systemctl is-enabled -q ssh.socket 2>/dev/null \
   && ! grep -qF ":$SSH_PORT (Stream)" <(systemctl show ssh.socket -p Listen --value 2>/dev/null); then
  systemctl restart ssh.socket
  fakt "ssh.socket" "перезапущен: порт сменён на $SSH_PORT"
fi
systemctl try-reload-or-restart ssh.service
svyaz "sshd reload"
grep -qE "[:.]$SSH_PORT +" <(ss -ltn) || upal "ssh не слушает порт $SSH_PORT после перезапуска — НЕ закрывай текущую сессию, смотри: systemctl status ssh.socket ssh.service"
cat > "$KOREN/etc/fail2ban/jail.d/ivanos.local" <<F2B
# IvanOS, stend-postavit.sh ‹zashchita-servera›
[sshd]
enabled = true
port = $SSH_PORT
backend = systemd
maxretry = 5
findtime = 10m
bantime = 1h
F2B
systemctl enable -q fail2ban
systemctl restart fail2ban
sleep 2
svyaz "fail2ban"
fail2ban-client status sshd >/dev/null 2>&1 || upal "fail2ban не поднял тюрьму sshd: journalctl -u fail2ban -n 30"
fakt "ssh" "только ключ, root без пароля, порт $SSH_PORT"
fakt "ufw" "входящие закрыты, открыто: $SSH_PORT${IVANOS_OTKRYT:+ $IVANOS_OTKRYT}"
fakt "fail2ban" "тюрьма sshd включена"
# ── ‹/zashchita-servera› ─────────────────────────────────────────────────────
}

