# было остановкой: ключ GitHub, вход в Claude, пароль бэкапа, Диск, токен. Теперь — одно окно;
# машина в это время ставит пакеты, Node, Chromium и Claude Code фоном. Ответы, уже данные
# (токен в .env-ivanos, пароль, ответ по n8n, вход), при повторе не спрашиваются заново.
# Пароль и токен НИКОГДА не печатаются: вопрос идёт мимо журнала, прямо в окно владельца.
