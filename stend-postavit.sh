# ── копия дома на GitHub ─────────────────────────────────────────────────────
# Псевдоним ssh, known_hosts и ключ заводятся раньше, в ‹github-dostup› (27-09): здесь
# их было поздно — дом к этому месту уже родился пустым. Сюда доходит и дом, поставленный
