# ── v2: шаги, время, фон ─────────────────────────────────────────────────────
# Время у каждой строки ставит main() — фильтром на всём выводе, а не каждая строка сама:
# куски этого файла пробы вынимают и зовут со своей обвязкой (shag/fakt/upal), и там времени
# не нужно.
vremya_na_stroku() { while IFS= read -r S; do printf '%s %s\n' "$(date +%H:%M:%S)" "$S"; done; }

# etap <имя> <функция> — сделанное пропускается, сделанное отмечается. Отметка ставится ПОСЛЕ
# функции: упал посередине — повтор начнёт шаг заново, а не пропустит недоделанное.
etap() {
  local IMYA=$1 F=$2
  if [ -f "$SOSTOYANIE/$IMYA.ok" ]; then
    fakt "шаг $IMYA" "сделан $(date -r "$SOSTOYANIE/$IMYA.ok" +'%d-%m %H:%M') — пропускаю"
    return 0
  fi
  shag "$IMYA"
  "$F"
  mkdir -p "$SOSTOYANIE"
  date +%s > "$SOSTOYANIE/$IMYA.ok"
}

