[Service]
Type=oneshot
Environment=PATH=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin
ExecStart=/usr/local/sbin/ivanos-backup.sh $R
BEKAPSL
  cat > "/etc/systemd/system/ivanos-backup-$R.timer" <<BEKAPTM
[Unit]
Description=IvanOS: бэкап $R по расписанию

[Timer]
OnCalendar=$KOGDA
RandomizedDelaySec=10min
Persistent=true

[Install]
WantedBy=timers.target
BEKAPTM
  systemd-analyze verify "/etc/systemd/system/ivanos-backup-$R.timer" >/dev/null 2>&1 \
    || upal "таймер бэкапа $R не прошёл systemd-analyze verify"
done
