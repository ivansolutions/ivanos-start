# ── Пакет: закрытая часть, по ЗАКРЕПЛЁННОМУ коммиту ──────────────────────────
# Решение владельца 28-09: пакет тянется по коммиту, закреплённому в загрузчике, а не по
# верхушке main: main меняется, а установка обязана быть той, что проверена.
f_paket() {
  if [ -d "$PAKET_PAPKA/dom" ] && [ -z "$PAKET_KOMMIT" ]; then
    fakt "пакет" "рядом со скриптом: $PAKET_PAPKA"; return 0
  fi
  [ -n "$PAKET_KOMMIT" ] || upal "пакета рядом нет, а коммит не закреплён (IVANOS_PAKET_KOMMIT) — ставить нечего"
  [ -d "$PAKET_PAPKA/.git" ] || git clone -q --no-checkout "$GITHUB_DOMA" "$PAKET_PAPKA" \
    || upal "пакет не клонируется из $REPO_GITHUB"
  git -C "$PAKET_PAPKA" fetch -q origin 2>/dev/null || true
  git -C "$PAKET_PAPKA" -c advice.detachedHead=false checkout -q --detach "$PAKET_KOMMIT" \
    || upal "в $REPO_GITHUB нет коммита $PAKET_KOMMIT (или в пакете правки мимо git)"
  [ "$(git -C "$PAKET_PAPKA" rev-parse HEAD)" = "$(git -C "$PAKET_PAPKA" rev-parse "$PAKET_KOMMIT^{commit}")" ] \
    || upal "пакет стоит не на закреплённом коммите"
  fakt "пакет" "$PAKET_PAPKA на $(git -C "$PAKET_PAPKA" rev-parse --short HEAD)"
}
